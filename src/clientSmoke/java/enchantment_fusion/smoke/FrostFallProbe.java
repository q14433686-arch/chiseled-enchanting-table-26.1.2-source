/**
 * Prepared, not yet run: real protection/death hooks and native effect invocation, but the
 * fall is injected through causeFallDamage rather than generated by physical movement.
 */
final class FrostFallProbe {
    private static final FusedPair WAVE = FusedPair.clean("minecraft:feather_falling", 4, "minecraft:frost_walker", 2);
    private static final FusedPair STEP = WAVE.flipped();
    private static final EquipmentSlot[] SLOTS = {EquipmentSlot.HEAD, EquipmentSlot.CHEST, EquipmentSlot.LEGS,
        EquipmentSlot.FEET, EquipmentSlot.MAINHAND, EquipmentSlot.OFFHAND};
    private FrostFallProbe() {}

    static void exercise(ServerPlayer player, BlockPos waterPos) {
        ServerLevel level = player.level();
        Holder<Enchantment> feather = enchant(level, "feather_falling");
        Holder<Enchantment> frost = enchant(level, "frost_walker");
        exerciseCarriers(player, feather, frost);

        List<ItemStack> savedSlots = new ArrayList<>();
        for (EquipmentSlot slot : SLOTS) savedSlots.add(player.getItemBySlot(slot));
        List<MobEffectInstance> savedEffects = player.getActiveEffects().stream().map(MobEffectInstance::new).toList();
        Vec3 oldPosition = player.position();
        float oldHealth = player.getHealth(), oldAbsorption = player.getAbsorptionAmount();
        int oldInvulnerability = player.invulnerableTime;
        boolean oldGround = player.onGround();
        GameType oldMode = player.gameMode.getGameModeForPlayer();
        Map<BlockPos, BlockState> savedBlocks = new LinkedHashMap<>();
        for (int x = -6; x <= 6; x++) for (int z = -6; z <= 6; z++) {
            BlockPos pos = waterPos.offset(x, 0, z);
            savedBlocks.put(pos, level.getBlockState(pos));
        }
        savedBlocks.put(waterPos.above(), level.getBlockState(waterPos.above()));
        boolean[] deny = {false};
        ServerLivingEntityEvents.ALLOW_DAMAGE.register((entity, source, amount) -> entity != player || !deny[0]);
        try {
            player.setGameMode(GameType.SURVIVAL);
            player.removeAllEffects();
            for (EquipmentSlot slot : SLOTS) player.setItemSlot(slot, ItemStack.EMPTY);
            ItemStack boots = new ItemStack(Items.DIAMOND_BOOTS);
            FusionStationOperations.applyFusedPairToGear(boots, WAVE, level.registryAccess());
            player.setItemSlot(EquipmentSlot.FEET, boots);
            player.setHealth(player.getMaxHealth());
            player.setAbsorptionAmount(0);
            player.invulnerableTime = 0;

            deny[0] = true;
            player.causeFallDamage(9.0D, 1.0F, level.damageSources().fall());
            require(!FrostFallSkills.releaseWave(player), "Cancelled fall damage must not create frost reserve");
            deny[0] = false;
            player.invulnerableTime = 0;
            float before = player.getHealth();
            player.causeFallDamage(9.0D, 1.0F, level.damageSources().fall());
            require(player.getHealth() < before && FrostFallSkills.releaseWave(player),
                "An accepted nonlethal fall with real Feather Falling must create a usable reserve");
            require(!FrostFallSkills.releaseWave(player), "Releasing a reserve must consume it exactly once");

            player.setItemSlot(EquipmentSlot.OFFHAND, new ItemStack(Items.TOTEM_OF_UNDYING));
            player.setHealth(1.0F);
            player.setAbsorptionAmount(0);
            player.invulnerableTime = 0;
            player.causeFallDamage(100.0D, 1.0F, level.damageSources().fall());
            require(player.isAlive() && player.getOffhandItem().isEmpty(), "The fixture must actually consume a vanilla totem");
            require(!FrostFallSkills.releaseWave(player), "A lethal fall saved by a totem must not store reserve");

            level.setBlockAndUpdate(waterPos, Blocks.WATER.defaultBlockState());
            level.setBlockAndUpdate(waterPos.above(), Blocks.AIR.defaultBlockState());
            player.teleportTo(waterPos.getX() + 0.5D, waterPos.getY() + 1.0D, waterPos.getZ() + 0.5D);
            player.setOnGround(true);
            ItemStack stepBoots = new ItemStack(Items.DIAMOND_BOOTS);
            FusionStationOperations.applyFusedPairToGear(stepBoots, STEP, level.registryAccess());
            player.setItemSlot(EquipmentSlot.FEET, stepBoots);
            EnchantmentHelper.runLocationChangedEffects(level, stepBoots, player, EquipmentSlot.FEET);
            require(level.getBlockState(waterPos).is(Blocks.WATER), "Selected Frost Walker direction must preserve original water");

            // A nested unrelated enchantment scope must mask, then restore, the guard.
            require(NativeFrostWaterGuard.enter(true), "A guarded scope must enter");
            try {
                require(NativeFrostWaterGuard.blocksWaterWrite(level, waterPos), "The guard must see water");
                boolean nested = NativeFrostWaterGuard.enter(false);
                try {
                    require(!NativeFrostWaterGuard.blocksWaterWrite(level, waterPos), "Unrelated nested scope must not inherit the guard");
                } finally { NativeFrostWaterGuard.exit(nested); }
                require(NativeFrostWaterGuard.blocksWaterWrite(level, waterPos), "Outer guard must be restored");
            } finally { NativeFrostWaterGuard.exit(true); }
            require(!NativeFrostWaterGuard.blocksWaterWrite(level, waterPos), "No scope may leak");

            EnchantmentHelper.stopLocationBasedEffects(stepBoots, player, EquipmentSlot.FEET);
            ItemStack ordinary = new ItemStack(Items.DIAMOND_BOOTS);
            ordinary.enchant(frost, 2);
            player.setItemSlot(EquipmentSlot.FEET, ordinary);
            EnchantmentHelper.runLocationChangedEffects(level, ordinary, player, EquipmentSlot.FEET);
            require(level.getBlockState(waterPos).is(Blocks.FROSTED_ICE),
                "Ordinary unfused Frost Walker must still freeze this same water cell");
            EnchantmentHelper.stopLocationBasedEffects(ordinary, player, EquipmentSlot.FEET);
        } finally {
            deny[0] = false;
            FrostFallSkills.onPlayerDisconnect(player.getUUID());
            for (Map.Entry<BlockPos, BlockState> entry : savedBlocks.entrySet()) level.setBlockAndUpdate(entry.getKey(), entry.getValue());
            for (int i = 0; i < SLOTS.length; i++) player.setItemSlot(SLOTS[i], savedSlots.get(i));
            player.removeAllEffects();
            for (MobEffectInstance effect : savedEffects) player.addEffect(effect);
            player.setGameMode(oldMode);
            player.setHealth(oldHealth);
            player.setAbsorptionAmount(oldAbsorption);
            player.invulnerableTime = oldInvulnerability;
            player.teleportTo(oldPosition.x, oldPosition.y, oldPosition.z);
            player.setOnGround(oldGround);
        }
    }

    private static void exerciseCarriers(ServerPlayer player, Holder<Enchantment> feather, Holder<Enchantment> frost) {
        for (FusedPair pair : List.of(WAVE, STEP)) {
            ItemStack boots = new ItemStack(Items.DIAMOND_BOOTS), shield = new ItemStack(Items.SHIELD);
            require(DirectionalHostRules.validateNewOrChanged(boots, pair) == RejectReason.NONE, "Worn boots must be supported");
            require(DirectionalHostRules.validateNewOrChanged(shield, pair) == RejectReason.UNSUPPORTED_DIRECTION_HOST,
                "An unsupported shield must be rejected");
            var socket = new SimpleContainer(4);
            socket.setItem(FusionStationOperations.SLOT_TARGET, shield);
            socket.setItem(FusionStationOperations.SLOT_PRIMARY, FusedEnchantedBookItem.createForPair(pair));
            require(FusionStationOperations.inspect(socket, player.level().registryAccess(), FusionStationOperations.TAB_SOCKET, -1, -1)
                .rejectReason() == RejectReason.UNSUPPORTED_DIRECTION_HOST, "Book socketing must reject a shield");
            socket.setItem(FusionStationOperations.SLOT_TARGET, boots);
            require(FusionStationOperations.inspect(socket, player.level().registryAccess(), FusionStationOperations.TAB_SOCKET, -1, -1)
                .executable(), "Book socketing must allow boots");
            var direct = new SimpleContainer(4);
            direct.setItem(FusionStationOperations.SLOT_TARGET, shield.copy());
            direct.setItem(FusionStationOperations.SLOT_PRIMARY, FusionStationOperations.createSingleEnchantedBook(
                FrostFallSkills.isWavePair(pair) ? feather : frost, pair.primaryLevel()));
            direct.setItem(FusionStationOperations.SLOT_SECONDARY, FusionStationOperations.createSingleEnchantedBook(
                FrostFallSkills.isWavePair(pair) ? frost : feather, pair.secondaryLevel()));
            require(FusionStationOperations.inspect(direct, player.level().registryAccess(), FusionStationOperations.TAB_SOCKET, 0, 1)
                .rejectReason() == RejectReason.UNSUPPORTED_DIRECTION_HOST, "Direct fusion must reject a shield");
            direct.setItem(FusionStationOperations.SLOT_TARGET, boots.copy());
            require(FusionStationOperations.inspect(direct, player.level().registryAccess(), FusionStationOperations.TAB_SOCKET, 0, 1)
                .executable(), "Direct fusion must allow boots");
            ItemStack legacy = new ItemStack(Items.SHIELD);
            legacy.set(FusionDataComponents.FUSED_PAIRS, FusedEnchantmentList.EMPTY.append(pair));
            String signature = FrostFallSkills.isWavePair(pair) ? FrostFallSkills.WAVE_SIGNATURE : FrostFallSkills.STEP_SIGNATURE;
            require(!FrostFallSkills.applies(pair, legacy, signature)
                && legacy.getOrDefault(FusionDataComponents.FUSED_PAIRS, FusedEnchantmentList.EMPTY).pairs().contains(pair),
                "Old unsupported gear must keep its old data and runtime path");
        }
    }

    private static Holder<Enchantment> enchant(ServerLevel level, String path) {
        return level.registryAccess().lookupOrThrow(Registries.ENCHANTMENT).getOrThrow(
            ResourceKey.create(Registries.ENCHANTMENT, Identifier.withDefaultNamespace(path)));
    }
    private static void require(boolean condition, String message) {
        if (!condition) throw new AssertionError(message);
    }
}
